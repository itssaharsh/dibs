import { chromium } from "@playwright/test";
const base = process.argv[2] ?? "http://localhost:3001";
const b = await chromium.launch();
const phone = async () => {
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 } });
  const p = await ctx.newPage();
  await p.goto(`${base}/d/latest`);
  return p;
};
const ps = await Promise.all([phone(), phone(), phone()]);
const btn = (p) => p.locator("div.fixed button").first();
for (const p of ps) await btn(p).filter({ hasText: /DIBS|Opens in/ }).waitFor({ timeout: 60000 });
console.log("ready", await Promise.all(ps.map((p) => btn(p).textContent())));
for (const p of ps) await btn(p).filter({ hasText: "DIBS" }).waitFor({ timeout: 30000 });
const t0 = Date.now();
await btn(ps[0]).click();
await new Promise((r) => setTimeout(r, 300));
await Promise.all([btn(ps[1]).click(), btn(ps[2]).click()]);
const labels = async () => Promise.all(ps.map((p) => btn(p).textContent()));
await btn(ps[0]).filter({ hasText: /PAY/ }).waitFor({ timeout: 20000 });
console.log("after claims", Date.now() - t0, "ms", await labels());
await btn(ps[0]).click();
await btn(ps[0]).filter({ hasText: /It's yours/ }).waitFor({ timeout: 20000 });
console.log("after pay", await labels());
await btn(ps[1]).filter({ hasText: /Withdraw/ }).waitFor({ timeout: 10000 });
await btn(ps[1]).click();
await btn(ps[1]).filter({ hasText: /Deposit back/ }).waitFor({ timeout: 20000 });
console.log("after withdraw", await labels());
await ps[0].screenshot({ path: `${process.env.SP}/bought.png` });
await ps[2].screenshot({ path: `${process.env.SP}/sold-other.png` });
await b.close();
